"""
Operational Package & Workflow API routes.
"""
from datetime import datetime, timezone
from uuid import UUID
from typing import Optional

from fastapi import APIRouter, Depends, HTTPException, status
from pydantic import BaseModel
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.database import get_db
from app.models.workflow import Workflow
from app.repositories import PackageRepository
from app.schemas.package import PackageGenerateResponse
from app.services import PackageGeneratorService, PackageGeneratorError
from app.services.agentic_workflow_service import (
    AgenticWorkflowService,
    AgenticWorkflowError,
)

router = APIRouter(prefix="/tasks", tags=["packages"])

class ResumeWorkflowRequest(BaseModel):
    workflow_id: str
    decision: str  # "approved" | "rejected" | "modified"
    action_id: str
    modified_action: Optional[dict] = None # NAYA

def get_package_generator(db: AsyncSession = Depends(get_db)) -> PackageGeneratorService:
    return PackageGeneratorService(db)

def get_package_repo(db: AsyncSession = Depends(get_db)) -> PackageRepository:
    return PackageRepository(db)

@router.post("/{task_id}/generate-package", response_model=PackageGenerateResponse)
async def generate_package(
    task_id: UUID,
    service: PackageGeneratorService = Depends(get_package_generator),
) -> PackageGenerateResponse:
    try:
        result = await service.generate_for_task(task_id)
    except PackageGeneratorError as e:
        raise HTTPException(status_code=400, detail=str(e))
    
    return PackageGenerateResponse(
        task_id=task_id,
        package_id=result["package_id"],
        version=result["version"],
        status=result["status"],
        generated_at=datetime.now(timezone.utc).isoformat(),
        sections_count=result["sections_count"],
        summary="Draft generated by system (LLM pending).",
    )

@router.get("/{task_id}/package")
async def get_latest_package(
    task_id: UUID,
    repo: PackageRepository = Depends(get_package_repo),
) -> dict:
    pkg = await repo.get_latest_for_task(task_id)
    if not pkg:
        raise HTTPException(status_code=404, detail=f"No package found for task {task_id}")
        
    return {
        "package_id": str(pkg.id),
        "task_id": str(pkg.task_id),
        "version": pkg.version,
        "status": pkg.status,
        "sections": pkg.sections,
        "summary": pkg.summary,
        "generated_by": pkg.generated_by,
        "created_at": pkg.created_at.isoformat(),
    }

@router.post("/{task_id}/initiate-workflow")
async def initiate_workflow(
    task_id: UUID,
    db: AsyncSession = Depends(get_db),
) -> dict:
    service = AgenticWorkflowService(db)
    try:
        result = await service.initiate_workflow(task_id)
        return result
    except AgenticWorkflowError as e:
        raise HTTPException(status_code=400, detail=str(e))

@router.post("/{task_id}/resume-workflow")
async def resume_workflow(
    task_id: UUID,
    payload: ResumeWorkflowRequest,
    db: AsyncSession = Depends(get_db),
) -> dict:
    service = AgenticWorkflowService(db)
    try:
        result = await service.resume_workflow(
            task_id=task_id,
            workflow_id=UUID(payload.workflow_id),
            decision=payload.decision,
            action_id=payload.action_id,
            modified_action=payload.modified_action # NAYA pass kiya
        )
        return result
    except AgenticWorkflowError as e:
        raise HTTPException(status_code=400, detail=str(e))

@router.get("/{task_id}/workflow")
async def get_workflow(
    task_id: UUID,
    db: AsyncSession = Depends(get_db),
) -> dict:
    stmt = select(Workflow).where(Workflow.task_id == task_id).order_by(Workflow.created_at.desc())
    workflow = (await db.execute(stmt)).scalars().first()
    
    if not workflow:
        raise HTTPException(status_code=404, detail="Workflow not found.")
        
    return {
        "workflow_id": str(workflow.id),
        "status": workflow.status,
        "created_at": workflow.created_at.isoformat(),
    }
from app.models.audit_log import AuditLog
from sqlalchemy import select, desc

@router.get(
    "/{task_id}/audit-logs",
    summary="Get Audit Logs for a task",
)
async def get_audit_logs(
    task_id: UUID,
    db: AsyncSession = Depends(get_db),
) -> dict:
    stmt = select(AuditLog).where(AuditLog.task_id == task_id).order_by(desc(AuditLog.created_at))
    logs = (await db.execute(stmt)).scalars().all()
    
    return {
        "total": len(logs),
        "logs": [
            {
                "id": str(log.id),
                "event_type": log.event_type,
                "actor": log.actor,
                "details": log.details,
                "timestamp": log.created_at.isoformat()
            } for log in logs
        ]
    }